def load_leaves(db):
    rows = db.query(JobCategory).filter(JobCategory.parent_id.isnot(None)).all()
    names = sorted({r.name for r in rows}, key=len, reverse=True)
    return names


def match_title(title, leaves):
    """返回 (std_leaf, strategy)。strategy: exact/substr/alias/substr_rule/None"""
    t = title.strip()
    tl = t.lower()

    # 1. 精确（大小写不敏感）
    for n in leaves:
        if n.lower() == tl:
            return n, "exact"

    # 2. 手工别名（精确标题）—— 优先于子串，避免"医药销售代表"被"销售代表"子串抢走
    if t in ALIASES:
        return ALIASES[t], "alias"

    # 3. 最长叶子子串（>=3 字；2 字叶子过于宽泛，仅走精确/别名）
    best, bestlen = None, 0
    for n in leaves:
        if len(n) >= 3 and n.lower() in tl and len(n) > bestlen:
            best, bestlen = n, len(n)
    if best:
        return best, "substr"

    # 4. 手工子串规则
    for raw, std in SUBSTR_RULES.items():
        if raw.lower() in tl:
            return std, "substr_rule"

    return None, None


def main():
    ap = argparse.ArgumentParser(description="扩充 synonym_dict")
    ap.add_argument("--apply", action="store_true", help="写入 synonym_dict（默认只生成报告）")
    args = ap.parse_args()

    db = SessionLocal()
    try:
        leaves = load_leaves(db)
        leaf_set = set(leaves)

        # 未归类标题
        rows = db.query(CleanedJob.title, CleanedJob.id).filter(CleanedJob.category_id.is_(None)).all()
        from collections import defaultdict
        title_counts = Counter(t for t, _ in rows)

        # 已存在的 synonym 键（大小写不敏感，匹配 DB 的 ci 排序规则）
        existing = {s.raw_word.lower() for s in db.query(SynonymDict).all()}

        proposed = {}
        proposed_lower = set()  # 防止大小写变体重复（DB uk_raw 不区分大小写）
        strat_count = Counter()
        unmatched = defaultdict(int)  # title -> count

        for title, cnt in title_counts.items():
            std, strat = match_title(title, leaves)
            if std and std in leaf_set:
                tl = title.lower()
                # 只新增尚不存在的 raw_word（已存在则可能是 orphan，另行处理）
                if tl not in existing and tl not in proposed_lower:
                    proposed[title] = std
                    proposed_lower.add(tl)
                    strat_count[strat] += cnt
            else:
                unmatched[title] = cnt

        total_unclass = sum(title_counts.values())
        covered = sum(title_counts[t] for t in proposed)
        strat_count["_unmatched"] = total_unclass - covered

        print(f"未归类记录: {total_unclass} 条 / {len(title_counts)} 种标题")
        print(f"叶子分类: {len(leaves)} 个 | 已存在 synonym: {len(existing)} 条")
        print(f"\n本次可新增 synonym: {len(proposed)} 条，覆盖 {covered} 条记录 ({covered/total_unclass*100:.1f}%)")
        print("  按策略:", dict(strat_count))
        print(f"  剩余未匹配: {len(unmatched)} 种标题 / {total_unclass-covered} 条\n")

        # 写出 JSON
        with open(OUT_JSON, "w", encoding="utf-8") as f:
            json.dump(proposed, f, ensure_ascii=False, indent=2)

        # 剩余 Top 80
        print("=== 剩余未匹配 Top 80 ===")
        for i, (t, c) in enumerate(sorted(unmatched.items(), key=lambda x: -x[1])[:80], 1):
            print(f"  {i:>3}. [{c:>4}] {t}")

        if args.apply:
            # 校验目标叶子存在后写入；用 INSERT IGNORE 让 DB 自行处理排序规则下的重复
            from sqlalchemy.dialects.mysql import insert as mysql_insert
            rows = [{"raw_word": r, "std_word": s} for r, s in proposed.items() if s in leaf_set]
            if rows:
                stmt = mysql_insert(SynonymDict.__table__).prefix_with("IGNORE").values(rows)
                db.execute(stmt)
                db.commit()
            print(f"\n已写入 {len(rows)} 条 synonym_dict（重复键由 DB 忽略）")
        else:
            print(f"\n(dry-run，未写入。加 --apply 写入) 建议文件: {OUT_JSON}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
